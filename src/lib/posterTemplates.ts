/** Colours and text of a template as a renderer spec (used by the gallery thumbnails). */
export function templateSpec(tpl: PosterTemplatePreset): PosterSpec {
  return {
    templateId: tpl.id,
    layout: tpl.layout,
    title: tpl.title,
    subtitle: tpl.subtitle,
    brand: tpl.brandName,
    footer: tpl.footerNote,
    showViewfinder: tpl.showViewfinder,
    showSteps: tpl.showStepsBadge,
    card: tpl.cardBgColor,
    text: tpl.cardTextColor,
    accent: tpl.accentColor,
    alt: tpl.altColor,
    icon: tpl.icon,
    pattern: tpl.pattern,
    chips: tpl.chips,
  };
}
