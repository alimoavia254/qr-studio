// Builds src/lib/posterIcons.ts: lucide icon outlines as single SVG path strings (24x24), so the
// poster canvas renderer can draw them with Path2D. Run: node scripts/gen-poster-icons.mjs
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const NAMES = [
  "wifi", "utensils", "coffee", "gift", "shopping-bag", "smartphone", "calendar-check", "ticket", "map-pin",
  "eighth-notes", "zap", "camera", "shield-check", "heart", "star", "users", "headphones", "cake-slice", "party-popper",
  "briefcase", "mail", "phone", "house", "key-round", "sparkles", "thumbs-up", "tag", "percent", "trophy",
  "bell-ring", "rocket", "mic-vocal", "pizza", "croissant", "wine", "life-buoy", "terminal", "qr-code", "message-circle",
];

const dir = "node_modules/lucide-react/dist/esm/icons";
const num = (v) => Number(v);

function circle(cx, cy, r) {
  return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`;
}
function rect(x, y, w, h, rx = 0) {
  rx = Math.min(rx, w / 2, h / 2);
  return `M${x + rx} ${y}h${w - 2 * rx}a${rx} ${rx} 0 0 1 ${rx} ${rx}v${h - 2 * rx}a${rx} ${rx} 0 0 1 ${-rx} ${rx}h${-(w - 2 * rx)}a${rx} ${rx} 0 0 1 ${-rx} ${-rx}v${-(h - 2 * rx)}a${rx} ${rx} 0 0 1 ${rx} ${-rx}z`;
}
function toPath([tag, a]) {
  switch (tag) {
    case "path": return a.d;
    case "circle": return circle(num(a.cx), num(a.cy), num(a.r));
    case "ellipse": return circle(num(a.cx), num(a.cy), num(a.rx));
    case "rect": return rect(num(a.x ?? 0), num(a.y ?? 0), num(a.width), num(a.height), num(a.rx ?? 0));
    case "line": return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case "polyline": return `M${a.points.trim().replace(/\s+/g, "L")}`.replace(/,/g, " ");
    case "polygon": return `M${a.points.trim().replace(/\s+/g, "L")}z`.replace(/,/g, " ");
    default: throw new Error("unsupported tag " + tag);
  }
}

const out = {};
for (const n of NAMES) {
  const mod = await import(pathToFileURL(path.resolve(dir, `${n}.mjs`)).href);
  out[n === "eighth-notes" ? "music" : n] = mod.__iconData.node.map(toPath).join("");
}
const body = Object.entries(out)
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join("\n");
fs.writeFileSync(
  "src/lib/posterIcons.ts",
  `// Generated by scripts/gen-poster-icons.mjs from lucide (ISC license). Do not edit by hand.\nexport const POSTER_ICONS: Record<string, string> = {\n${body}\n};\n`
);
console.log("wrote", Object.keys(out).length, "icons");
